/**
 * Track catalogue. Each entry is pure data: a centreline (control points the
 * Catmull-Rom curve passes through), the road dimensions, and a `theme` that
 * tells track.js which scenery/material set to build. createTrack() consumes
 * one of these — see track.js.
 *
 * Coordinates are metres in the XZ plane (y is always 0; the car drives on a
 * flat physics plane, so "mountains" etc. are scenery, not real elevation).
 * controlPoints[0] is the start/finish; the points around it are collinear so
 * the Catmull tangents settle onto a straight where the grid is painted.
 *
 * Every road circuit is the REAL LAYOUT of the F1 venue it is named for
 * (owner direction, 2026-09-01: "use F1 tracks as inspiration"), traced from
 * the published centreline and brought down to a scale the ~480 hp GT can
 * lap in about 70-80 s:
 *
 *   - the centreline is scaled uniformly (0.42-0.63 depending on the venue),
 *     rotated so the start straight heads +z, and resampled at 3 m;
 *   - every corner tighter than 20 m radius is opened out (the car's steering
 *     lock and the Catmull-Rom sampling both misbehave below ~18 m), so the
 *     hairpins are rounder than the originals but every corner sequence,
 *     straight and chicane is where it is on the real map;
 *   - sections that come closer than 2 × the barrier offset are eased apart
 *     so the armco of one never lands on the road of another;
 *   - control points are then picked densely on the corners (~9-16 m) and
 *     sparsely on the straights (~40 m). That uneven spacing is why every
 *     circuit uses the CENTRIPETAL Catmull-Rom parametrisation: the uniform
 *     one kinks and loops wherever the spacing steps at a corner entry.
 *
 * The one deliberate exception is SUNSET SPEEDWAY: a literal perfect oval
 * (owner-requested — "should look like a circle"), whose points lie ON an
 * exact stadium (two short straights + two 200 m-radius semicircles) at 15°
 * steps. Keep it geometric; don't hand-wobble it.
 *
 * Don't reintroduce procedural layout generators into the game: the points
 * below are literal data, and the game never re-derives them. Verify any
 * edit with scripts/track-geometry.mjs: min corner radius ≥ ~18 m, and
 * non-adjacent road sections at least 2 × (roadWidth/2 + runoff + 0.5) apart
 * so barriers never overlap. The frame count scales with lap length (see
 * segmentsForLength below) so per-frame curvature thresholds stay valid.
 */

/**
 * Centreline samples for a circuit of `len` metres. Everything that reads
 * per-frame curvature (kerb and gravel thresholds, the racing-line weave, the
 * AI's look-ahead in frames, the barrier box stride) was tuned at ~2.2 m
 * between frames on the original 1.3 km layouts, so the count follows lap
 * length to hold that spacing instead of stretching the samples.
 */
export function segmentsForLength(len) {
  return Math.max(400, Math.min(1800, Math.round(len / 2.2)));
}

